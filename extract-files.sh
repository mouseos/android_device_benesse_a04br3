#!/usr/bin/env bash
# Copy the MediaTek vendor blobs listed in proprietary-files.txt from a BSP
# product output directory and write vendor/benesse/TAB-A04-BR3.
#   extract-files.sh <BSP product out dir> [<AOSP top>]
# The BSP output is the aiot8362am3_64_bsp vendor build of the MT8167
# Android 10 BSP with the TAB-A04-BR3 MT6630 project values.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
src=$(cd "$1" && pwd)
top=${2:-$(cd "$here/../../.." && pwd)}
dst="$top/vendor/benesse/TAB-A04-BR3"
rm -rf "$dst/proprietary"
mkdir -p "$dst/proprietary"
mk="$dst/TAB-A04-BR3-vendor.mk"
{
    echo "# Generated by device/benesse/TAB-A04-BR3/extract-files.sh; do not edit."
    echo "# Source: $src"
    echo "PRODUCT_COPY_FILES += \\"
} > "$mk"
n=0
while IFS= read -r line; do
    f=${line%%#*}; f=${f//[[:space:]]/}
    [[ -n $f ]] || continue
    if [[ ! -e "$src/$f" ]]; then echo "missing: $f" >&2; exit 1; fi
    mkdir -p "$dst/proprietary/$(dirname "$f")"
    cp -L --preserve=mode "$src/$f" "$dst/proprietary/$f"
    echo "    vendor/benesse/TAB-A04-BR3/proprietary/$f:\$(TARGET_COPY_OUT_VENDOR)/${f#vendor/} \\" >> "$mk"
    n=$((n+1))
done < "$here/proprietary-files.txt"
echo "" >> "$mk"
printf '%s\n' "# Generated by extract-files.sh" > "$dst/BoardConfigVendor.mk"
echo "$n files -> $dst"
