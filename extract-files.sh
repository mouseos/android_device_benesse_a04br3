#!/usr/bin/env bash
# Copy the MediaTek vendor blobs listed in proprietary-files.txt from a BSP
# product output directory and write vendor/benesse/a04br3.
#   extract-files.sh <BSP product out dir> [<AOSP top>]
# The BSP output is the aiot8362am3_64_bsp vendor build of the MT8167
# Android 10 BSP with the TAB-A04-BR3 MT6630 project values.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
src=$(cd "$1" && pwd)
top=${2:-$(cd "$here/../../.." && pwd)}
dst="$top/vendor/benesse/a04br3"
rm -rf "$dst/proprietary"
mkdir -p "$dst/proprietary"
mk="$dst/a04br3-vendor.mk"
{
    echo "# Generated by device/benesse/a04br3/extract-files.sh; do not edit."
    echo "# Source: BSP out/target/product/$(basename "$src")"
    echo "PRODUCT_COPY_FILES += \\"
} > "$mk"
n=0
apks=()
printf '%s\n' "# Generated by extract-files.sh; do not edit." "LOCAL_PATH := \$(call my-dir)" "ifeq (\$(TARGET_DEVICE),a04br3)" > "$dst/Android.mk"
while IFS= read -r line; do
    f=${line%%#*}; f=${f//[[:space:]]/}
    [[ -n $f ]] || continue
    if [[ ! -e "$src/$f" ]]; then echo "missing: $f" >&2; exit 1; fi
    mkdir -p "$dst/proprietary/$(dirname "$f")"
    cp -L --preserve=mode "$src/$f" "$dst/proprietary/$f"
    if [[ $f == *.apk ]]; then
        # APKs cannot go through PRODUCT_COPY_FILES; install them as
        # presigned prebuilt modules in the same directory.
        name=$(basename "$f" .apk)
        rel=$(dirname "${f#vendor/}")
        cat >> "$dst/Android.mk" <<EOM

include \$(CLEAR_VARS)
LOCAL_MODULE := $name
LOCAL_MODULE_CLASS := APPS
LOCAL_SRC_FILES := proprietary/$f
LOCAL_CERTIFICATE := PRESIGNED
LOCAL_MODULE_SUFFIX := .apk
LOCAL_MODULE_PATH := \$(TARGET_OUT_VENDOR)/$rel
LOCAL_DEX_PREOPT := false
include \$(BUILD_PREBUILT)
EOM
        apks+=("$name")
    else
        echo "    vendor/benesse/a04br3/proprietary/$f:\$(TARGET_COPY_OUT_VENDOR)/${f#vendor/} \\" >> "$mk"
    fi
    n=$((n+1))
done < "$here/proprietary-files.txt"
echo "" >> "$mk"
echo "endif" >> "$dst/Android.mk"
(( ${#apks[@]} )) && echo "PRODUCT_PACKAGES += ${apks[*]}" >> "$mk"
printf '%s\n' "# Generated by extract-files.sh" > "$dst/BoardConfigVendor.mk"
echo "$n files -> $dst"
